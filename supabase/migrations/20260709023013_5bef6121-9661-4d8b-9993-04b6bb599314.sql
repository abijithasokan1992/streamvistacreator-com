
-- ============ ENUMS ============
DO $$ BEGIN
  CREATE TYPE public.distribution_protocol AS ENUM ('api','ftp','sftp','aspera','signiant','s3','http_webhook');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.distribution_package_status AS ENUM ('draft','building','ready','archived','failed');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.distribution_queue_status AS ENUM ('queued','dispatching','delivered','failed','cancelled','retrying');
