-- ============================================================================
-- College ERP Database Schema for Oracle Cloud Infrastructure (ATP) & APEX
-- Phase 3 - Design the Database
-- ============================================================================

-- 1. Colleges Table (Tenant Configuration)
CREATE TABLE colleges (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_colleges PRIMARY KEY,
    name          VARCHAR2(255) NOT NULL,
    domain        VARCHAR2(100) UNIQUE,
    address       VARCHAR2(500),
    contact_phone VARCHAR2(20),
    contact_email VARCHAR2(150),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. Roles Table
CREATE TABLE roles (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_roles PRIMARY KEY,
    name        VARCHAR2(50) NOT NULL CONSTRAINT uq_role_name UNIQUE,
    description VARCHAR2(255)
);

-- 3. Users Table (Unified accounts across the college tenancy)
CREATE TABLE users (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_users PRIMARY KEY,
    college_id    NUMBER NOT NULL,
    role_id       NUMBER NOT NULL,
    email         VARCHAR2(150) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    first_name    VARCHAR2(100) NOT NULL,
    last_name     VARCHAR2(100) NOT NULL,
    status        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_users_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id),
    CONSTRAINT uq_user_college_email UNIQUE (college_id, email),
    CONSTRAINT chk_user_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

-- Create index for faster authentication lookup
CREATE INDEX idx_users_auth ON users (email, status);

-- 4. Departments Table
CREATE TABLE departments (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_departments PRIMARY KEY,
    college_id  NUMBER NOT NULL,
    name        VARCHAR2(150) NOT NULL,
    code        VARCHAR2(20) NOT NULL,
    CONSTRAINT fk_departments_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT uq_dept_college_code UNIQUE (college_id, code)
);

-- 5. Courses Table
CREATE TABLE courses (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_courses PRIMARY KEY,
    college_id    NUMBER NOT NULL,
    department_id NUMBER NOT NULL,
    name          VARCHAR2(150) NOT NULL,
    code          VARCHAR2(20) NOT NULL,
    credits       NUMBER(2) DEFAULT 3 NOT NULL,
    CONSTRAINT fk_courses_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_courses_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE CASCADE,
    CONSTRAINT uq_course_college_code UNIQUE (college_id, code)
);

-- 6. Academic Years Table
CREATE TABLE academic_years (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_academic_years PRIMARY KEY,
    college_id NUMBER NOT NULL,
    name       VARCHAR2(50) NOT NULL,
    start_date DATE NOT NULL,
    end_date   DATE NOT NULL,
    is_active  CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT fk_academic_years_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT chk_ay_is_active CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT chk_ay_dates CHECK (start_date < end_date)
);

-- 7. Students Table
CREATE TABLE students (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_students PRIMARY KEY,
    user_id          NUMBER NOT NULL CONSTRAINT uq_student_user UNIQUE,
    college_id       NUMBER NOT NULL,
    department_id    NUMBER NOT NULL,
    course_id        NUMBER NOT NULL,
    academic_year_id NUMBER NOT NULL,
    admission_number VARCHAR2(50) NOT NULL,
    roll_number      VARCHAR2(50),
    date_of_birth    DATE,
    phone_number     VARCHAR2(20),
    photo_url        VARCHAR2(500),
    CONSTRAINT fk_students_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_students_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_students_dept FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_students_course FOREIGN KEY (course_id) REFERENCES courses(id),
    CONSTRAINT fk_students_ay FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
    CONSTRAINT uq_student_admission UNIQUE (college_id, admission_number)
);

-- 8. Faculty Table
CREATE TABLE faculty (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_faculty PRIMARY KEY,
    user_id       NUMBER NOT NULL CONSTRAINT uq_faculty_user UNIQUE,
    college_id    NUMBER NOT NULL,
    department_id NUMBER NOT NULL,
    designation   VARCHAR2(100) NOT NULL,
    qualification VARCHAR2(255) NOT NULL,
    phone_number  VARCHAR2(20),
    CONSTRAINT fk_faculty_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_faculty_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_faculty_dept FOREIGN KEY (department_id) REFERENCES departments(id)
);

-- 9. Admissions Table
CREATE TABLE admissions (
    id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_admissions PRIMARY KEY,
    college_id   NUMBER NOT NULL,
    first_name   VARCHAR2(100) NOT NULL,
    last_name    VARCHAR2(100) NOT NULL,
    email        VARCHAR2(150) NOT NULL,
    phone        VARCHAR2(20),
    course_id    NUMBER NOT NULL,
    status       VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    reviewed_by  NUMBER,
    remarks      VARCHAR2(500),
    CONSTRAINT fk_admissions_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_admissions_course FOREIGN KEY (course_id) REFERENCES courses(id),
    CONSTRAINT fk_admissions_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),
    CONSTRAINT chk_admission_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'WAITLISTED'))
);

-- 10. Attendance Table
CREATE TABLE attendance (
    id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_attendance PRIMARY KEY,
    student_id      NUMBER NOT NULL,
    course_id       NUMBER NOT NULL,
    faculty_id      NUMBER NOT NULL,
    attendance_date DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    status          CHAR(1) NOT NULL,
    remarks         VARCHAR2(255),
    CONSTRAINT fk_attendance_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE CASCADE,
    CONSTRAINT chk_attendance_status CHECK (status IN ('P', 'A', 'L', 'O')), -- Present, Absent, Late, Other
    CONSTRAINT uq_attendance_entry UNIQUE (student_id, course_id, attendance_date)
);

CREATE INDEX idx_attendance_date ON attendance(attendance_date);

-- 11. Timetable Table
CREATE TABLE timetable (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_timetable PRIMARY KEY,
    college_id       NUMBER NOT NULL,
    department_id    NUMBER NOT NULL,
    course_id        NUMBER NOT NULL,
    faculty_id       NUMBER NOT NULL,
    academic_year_id NUMBER NOT NULL,
    day_of_week      NUMBER(1) NOT NULL,
    start_time       VARCHAR2(8) NOT NULL, -- e.g. "09:00"
    end_time         VARCHAR2(8) NOT NULL, -- e.g. "09:50"
    classroom        VARCHAR2(50),
    CONSTRAINT fk_timetable_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_dept FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_timetable_course FOREIGN KEY (course_id) REFERENCES courses(id),
    CONSTRAINT fk_timetable_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id),
    CONSTRAINT fk_timetable_ay FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
    CONSTRAINT chk_timetable_day CHECK (day_of_week BETWEEN 1 AND 7)
);

-- 12. Exams Table
CREATE TABLE exams (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_exams PRIMARY KEY,
    college_id       NUMBER NOT NULL,
    course_id        NUMBER NOT NULL,
    academic_year_id NUMBER NOT NULL,
    name             VARCHAR2(100) NOT NULL,
    exam_date        DATE NOT NULL,
    max_marks        NUMBER(5,2) NOT NULL,
    min_marks        NUMBER(5,2) NOT NULL,
    CONSTRAINT fk_exams_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_exams_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_exams_ay FOREIGN KEY (academic_year_id) REFERENCES academic_years(id) ON DELETE CASCADE
);

-- 13. Marks Table
CREATE TABLE marks (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_marks PRIMARY KEY,
    exam_id        NUMBER NOT NULL,
    student_id     NUMBER NOT NULL,
    marks_obtained NUMBER(5,2) NOT NULL,
    grade          VARCHAR2(5),
    remarks        VARCHAR2(255),
    CONSTRAINT fk_marks_exam FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE,
    CONSTRAINT fk_marks_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT uq_marks_student_exam UNIQUE (exam_id, student_id),
    CONSTRAINT chk_marks_obtained CHECK (marks_obtained >= 0)
);

-- 14. Fee Structure Table
CREATE TABLE fee_structure (
