-- Trigger to calculate and update grades automatically in Marks Table based on Marks Obtained
CREATE OR REPLACE TRIGGER trg_auto_grade_calculation
BEFORE INSERT OR UPDATE ON marks
FOR EACH ROW
DECLARE
    v_max_marks NUMBER(5,2);
    v_percentage NUMBER(5,2);
BEGIN
    SELECT max_marks INTO v_max_marks
    FROM exams
    WHERE id = :NEW.exam_id;
    
    IF v_max_marks > 0 THEN
        v_percentage := (:NEW.marks_obtained / v_max_marks) * 100;
        
        IF v_percentage >= 90 THEN
            :NEW.grade := 'A+';
        ELSIF v_percentage >= 80 THEN
            :NEW.grade := 'A';
        ELSIF v_percentage >= 70 THEN
            :NEW.grade := 'B';
        ELSIF v_percentage >= 60 THEN
            :NEW.grade := 'C';
        ELSIF v_percentage >= 50 THEN
            :NEW.grade := 'D';
        ELSE
            :NEW.grade := 'F';
        END IF;
    ELSE
        :NEW.grade := 'I'; -- Incomplete / Invalid
    END IF;
END;
