-- ============ updated_at triggers ============
CREATE OR REPLACE FUNCTION public.tg_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END; $$;

DO $$ BEGIN
  CREATE TRIGGER trg_distribution_partners_touch BEFORE UPDATE ON public.distribution_partners
    FOR EACH ROW EXECUTE FUNCTION public.tg_touch_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TRIGGER trg_distribution_mappings_touch BEFORE UPDATE ON public.distribution_metadata_mappings
    FOR EACH ROW EXECUTE FUNCTION public.tg_touch_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TRIGGER trg_distribution_packages_touch BEFORE UPDATE ON public.distribution_packages
    FOR EACH ROW EXECUTE FUNCTION public.tg_touch_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TRIGGER trg_distribution_queue_touch BEFORE UPDATE ON public.distribution_queue
    FOR EACH ROW EXECUTE FUNCTION public.tg_touch_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE TRIGGER trg_distribution_deliveries_touch BEFORE UPDATE ON public.distribution_deliveries
    FOR EACH ROW EXECUTE FUNCTION public.tg_touch_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ============ RPC: retry failed deliveries ============
CREATE OR REPLACE FUNCTION public.retry_failed_distribution_deliveries(_title_id uuid DEFAULT NULL)
RETURNS int
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_count int;
BEGIN
  IF NOT (public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'super_admin')
          OR EXISTS (SELECT 1 FROM public.content_titles t WHERE t.id = _title_id AND t.owner_user_id = auth.uid())) THEN
    RAISE EXCEPTION 'not_authorized';
  END IF;

  UPDATE public.distribution_queue
     SET status = 'retrying',
         attempts = 0,
         next_retry_at = now(),
         last_error = NULL,
         last_error_code = NULL
   WHERE status = 'failed'
     AND (_title_id IS NULL OR title_id = _title_id);
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.retry_failed_distribution_deliveries(uuid) FROM public;
GRANT EXECUTE ON FUNCTION public.retry_failed_distribution_deliveries(uuid) TO authenticated;
