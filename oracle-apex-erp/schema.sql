-- Trigger to adjust available library book stock upon checkout or return
CREATE OR REPLACE TRIGGER trg_book_stock_update
AFTER INSERT OR UPDATE ON book_issues
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.status = 'ISSUED' THEN
            UPDATE library_books
            SET available = available - 1
            WHERE id = :NEW.book_id;
        END IF;
    ELSIF UPDATING THEN
        IF :OLD.status = 'ISSUED' AND :NEW.status = 'RETURNED' THEN
            UPDATE library_books
            SET available = available + 1
            WHERE id = :NEW.book_id;
        ELSIF :OLD.status = 'RETURNED' AND :NEW.status = 'ISSUED' THEN
            UPDATE library_books
            SET available = available - 1
            WHERE id = :NEW.book_id;
        END IF;
    END IF;
END;
