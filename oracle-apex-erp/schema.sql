    amount           NUMBER(12,2) NOT NULL,
    due_date         DATE NOT NULL,
    CONSTRAINT fk_fee_struct_college FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE CASCADE,
    CONSTRAINT fk_fee_struct_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
