-- 15. Fee Payments Table
CREATE TABLE fee_payments (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_fee_payments PRIMARY KEY,
    student_id       NUMBER NOT NULL,
    fee_structure_id NUMBER NOT NULL,
    amount_paid      NUMBER(12,2) NOT NULL,
    payment_date     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    payment_method   VARCHAR2(50) NOT NULL, -- e.g. "Razorpay", "Card", "NetBanking", "Cash"
